// Run after editing creative.html or artist.html:
// node tools/build-transition-pages.mjs
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pages = {};
for (const name of ["index.html", "creative.html", "artist.html"]) {
  const html = await fs.readFile(path.join(root, name), "utf8");
  const [, attributes, body] = html.match(/<body([^>]*)>([\s\S]*?)<\/body>/i);
  pages[name] = {
    title: html.match(/<title>([\s\S]*?)<\/title>/i)[1],
    description:
      html.match(/name="description"\s+content="([^"]*)"/i)?.[1] || "",
    bodyClass: attributes.match(/class="([^"]*)"/)?.[1] || "",
    body,
  };
}
await fs.writeFile(
  path.join(root, "agency-pages.js"),
  "// Generated by tools/build-transition-pages.mjs — edit the HTML pages.\nwindow.SendReturnAgencyPages = " +
    JSON.stringify(pages) +
    ";\n",
);
console.log("Agency transition content rebuilt.");
